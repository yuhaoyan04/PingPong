"""Estimate sphere angular velocity from local planes in ball-centred events.

This experimental estimator does not detect or identify dots.  In a small
space-time neighbourhood, events generated by one moving contrast edge lie on
an approximate plane t = a*x + b*y + c.  Its normal-flow constraint is linear
in the angular velocity of a projected unit sphere, allowing thousands of
short marker-edge fragments to vote for one rigid rotation.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from pingpong_event_pipeline.events import RawWindowReader


def normalized_events(raw: str, path_file: str, inner_radius: float):
    path = np.load(path_file)
    timestamps = path["timestamps_us"].astype(np.int64)
    centers = path["centers_px"].astype(np.float64)
    radii = path["radii_px"].astype(np.float64)
    reader = RawWindowReader(raw)
    events = reader.window(int(timestamps[0]), int(timestamps[-1] + 1))
    t = events["timestamp"].astype(np.int64)
    cx = np.interp(t, timestamps, centers[:, 0])
    cy = np.interp(t, timestamps, centers[:, 1])
    radius = np.interp(t, timestamps, radii)
    x = (events["x"].astype(np.float64) - cx) / radius
    y = (events["y"].astype(np.float64) - cy) / radius
    keep = x * x + y * y <= inner_radius * inner_radius
    return x[keep], y[keep], t[keep], events["polarity"][keep].astype(np.int8)


def collect_planes(x, y, timestamps, polarity, chunk_us=4000,
                   cell_size=.14, minimum_events=20, maximum_events=450,
                   maximum_time_residual_us=180.0):
    if not len(timestamps):
        return np.empty((0, 3)), []
    t0 = int(timestamps.min())
    chunk = ((timestamps - t0) // chunk_us).astype(np.int32)
    gx = np.floor((x + 1.0) / cell_size).astype(np.int32)
    gy = np.floor((y + 1.0) / cell_size).astype(np.int32)
    keys = np.column_stack((chunk, polarity, gx, gy))
    order = np.lexsort((gy, gx, polarity, chunk))
    keys = keys[order]; x = x[order]; y = y[order]; timestamps = timestamps[order]
    boundaries = np.r_[0, 1 + np.flatnonzero(np.any(keys[1:] != keys[:-1], axis=1)), len(keys)]
    equations = []; records = []
    for start, stop in zip(boundaries[:-1], boundaries[1:]):
        count = stop - start
        if count < minimum_events or count > maximum_events:
            continue
        xx = x[start:stop]; yy = y[start:stop]
        tt = (timestamps[start:stop] - np.median(timestamps[start:stop])) * 1e-6
        design = np.column_stack((xx - np.mean(xx), yy - np.mean(yy),
                                  np.ones(count)))
        if np.linalg.cond(design) > 80:
            continue
        coefficient = np.linalg.lstsq(design, tt, rcond=None)[0]
        residual_us = 1e6 * np.median(np.abs(tt - design @ coefficient))
        if residual_us > maximum_time_residual_us:
            continue
        a, b = coefficient[:2]
        gradient = float(np.hypot(a, b))
        if not 5e-4 <= gradient <= .20:
            continue
        px, py = float(np.mean(xx)), float(np.mean(yy))
        z = float(np.sqrt(max(1e-6, 1.0 - px * px - py * py)))
        equation = np.array([-b * z, a * z, -a * py + b * px], np.float64)
        if np.linalg.norm(equation) < 1e-6:
            continue
        equations.append(equation)
        records.append({"x": px, "y": py, "events": int(count),
                        "plane_residual_us": float(residual_us)})
    return np.asarray(equations, np.float64).reshape(-1, 3), records


def robust_solve(equations: np.ndarray, maximum_rpm: float, seed: int = 51,
                 hypotheses: int = 6000, threshold: float = .28):
    if len(equations) < 20:
        return np.zeros(3), np.zeros(len(equations), bool), None
    rng = np.random.default_rng(seed)
    maximum = maximum_rpm * 2 * np.pi / 60.0
    best = None
    for _ in range(hypotheses):
        sample = rng.choice(len(equations), 3, replace=False)
        try:
            omega = np.linalg.solve(equations[sample], np.ones(3))
        except np.linalg.LinAlgError:
            continue
        if not np.isfinite(omega).all() or np.linalg.norm(omega) > maximum:
            continue
        residual = np.abs(equations @ omega - 1.0)
        inliers = residual <= threshold
        count = int(np.count_nonzero(inliers))
        key = (count, -float(np.median(residual[inliers])) if count else -np.inf)
        if best is None or key > best[0]:
            best = (key, omega, inliers)
    if best is None or np.count_nonzero(best[2]) < 12:
        return np.zeros(3), np.zeros(len(equations), bool), None
    inliers = best[2]
    omega = best[1]
    for _ in range(6):
        residual = equations[inliers] @ omega - 1.0
        scale = 1.4826 * np.median(np.abs(residual - np.median(residual))) + .02
        weights = np.minimum(1.0, 1.5 * scale / np.maximum(np.abs(residual), 1e-9))
        root = np.sqrt(weights)
        omega = np.linalg.lstsq(equations[inliers] * root[:, None], root, rcond=None)[0]
        residual_all = np.abs(equations @ omega - 1.0)
        inliers = residual_all <= threshold
    residual_all = np.abs(equations @ omega - 1.0)
    return omega, inliers, residual_all


def main():
    parser = argparse.ArgumentParser(description="球心事件局部平面刚性旋转估计")
    parser.add_argument("--raw", required=True)
    parser.add_argument("--path", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--inner-radius", type=float, default=.72)
    parser.add_argument("--chunk-us", type=int, default=4000)
    parser.add_argument("--cell-size", type=float, default=.14)
    parser.add_argument("--minimum-events", type=int, default=20)
    parser.add_argument("--maximum-events", type=int, default=450)
    parser.add_argument("--maximum-plane-residual-us", type=float, default=180)
    parser.add_argument("--maximum-rpm", type=float, default=15000)
    args = parser.parse_args()
    x, y, timestamps, polarity = normalized_events(
        args.raw, args.path, args.inner_radius)
    equations, records = collect_planes(
        x, y, timestamps, polarity, args.chunk_us, args.cell_size,
        args.minimum_events, args.maximum_events,
        args.maximum_plane_residual_us)
    omega, inliers, residual = robust_solve(equations, args.maximum_rpm)
    magnitude = float(np.linalg.norm(omega))
    report = {
        "purpose": "event_plane_rigid_sphere_rotation_candidate",
        "events_inside_ball": int(len(x)),
        "local_planes": int(len(equations)),
        "inlier_planes": int(np.count_nonzero(inliers)),
        "inlier_fraction": float(np.mean(inliers)) if len(inliers) else 0.0,
        "rpm": magnitude * 60.0 / (2 * np.pi) if magnitude else None,
        "axis_camera": (omega / magnitude).tolist() if magnitude else None,
        "equation_residual_median": (float(np.median(residual[inliers]))
                                      if residual is not None and np.any(inliers) else None),
        "parameters": vars(args),
        "status": "candidate_requires_dual_camera_and_parameter_stability",
    }
    output = Path(args.output); output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    np.savez(output.with_suffix(".npz"), equations=equations, omega_rad_s=omega,
             inliers=inliers)
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
